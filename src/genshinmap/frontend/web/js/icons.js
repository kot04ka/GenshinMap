// Кликабельный div/span — доступен с клавиатуры: Tab + Enter/пробел (см. app.js)
function kbButton(el) { el.setAttribute('role', 'button'); el.tabIndex = 0; return el; }

function ICON(name, cls) {
  const p = ICON_PATHS[name];
  if (!p) return '';
  return `<svg class="ic${cls ? ' ' + cls : ''}" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${p}</svg>`;
}

// Иконка для CSS (background-image) — значки уровней/заданий на маркерах
function iconDataUrl(name, color) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="${color}" ` +
    `stroke-width="2.4" stroke-linecap="round" stroke-linejoin="round">${ICON_PATHS[name]}</svg>`;
  return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
}
